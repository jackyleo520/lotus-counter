    match = re.match(r'"(\d{4})\s+(.*)"', line)
    if not match:
        continue

    date_str = match.group(1)
    content = match.group(2)

    # 解析月份和日期
    month = int(date_str[:2])
    day = int(date_str[2:])

    # 特殊处理除夕 (0100)
    if day == 0:
        month = 12
        day = 30

    key = f"{month}-{day}"
    events = []

    # 分割内容
    parts = re.split(r'[，又、，]', content)

    for part in parts:
        part = part.strip()
        if not part:
            continue

        # 检查是否是节日
        if part in festival_events:
            events.append(f"{festival_events[part]}:{part}")
        # 检查是否是已知事件类型
        elif part in event_types:
            events.append(f"{event_types[part]}:{part}")
        # 检查是否包含"诞"字（诞辰）
        elif '诞' in part and '圣诞' not in part:
            events.append(f"yindu:{part}")
        # 检查是否包含"忌"字
        elif '忌' in part and part != '五虚忌':
            events.append(f"fanhai:{part}")
        # 检查是否包含"斋"字
        elif '斋' in part and part != '观音斋' and part != '地藏斋':
            events.append(f"fanhai:{part}")

    if events:
        if key not in lunar_events:
            lunar_events[key] = []
        lunar_events[key].extend(events)

