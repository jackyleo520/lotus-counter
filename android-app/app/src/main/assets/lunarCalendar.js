    // 农历节日 map：key "MM-DD" -> 完整说明文本
    var LunarFestivalMap = {};
    (function () {
        for (var j = 0; j < lFtv.length; j++) {
            var m = lFtv[j].match(/^(\d{2})(\d{2})[\s\*]+(.+)$/);
            if (!m) continue;
            LunarFestivalMap[m[1] + '-' + m[2]] = m[3];
        }
    })();

    // 阳历节日 map：key "MM-DD" -> 名称
    var SolarFestivalMap = {};
    (function () {
        for (var j = 0; j < sFtv.length; j++) {
            var m = sFtv[j].match(/^(\d{2})(\d{2})\*?\s*(.+)$/);
            if (!m) continue;
            SolarFestivalMap[m[1] + '-' + m[2]] = m[3];
        }
    })();

    // 根据节日文本判断类型（对应日历中已定义的彩色圆点样式）
    function deriveEventType(t) {
        if (t.indexOf('圣诞') > -1) return 'festival';
        if (t.indexOf('观音斋') > -1) return 'guanyin';
        if (t.indexOf('地藏斋') > -1) return 'dizang';
        if (t.indexOf('斋') > -1) return 'shizhai';
        if (t.indexOf('佛欢喜日') > -1 || t.indexOf('腊八') > -1 || t.indexOf('成道') > -1 ||
            t.indexOf('涅槃') > -1 || t.indexOf('出家') > -1 || t.indexOf('诞') > -1) return 'festival';
        if (t.indexOf('四天王') > -1) return 'sitianwang';
        if (t.indexOf('九毒') > -1) return 'jiudu';
        if (t.indexOf('天地仓') > -1 || t.indexOf('天仓') > -1) return 'tiancang';
        if (t.indexOf('斗降') > -1 || t.indexOf('北斗') > -1) return 'dougong';
        if (t.indexOf('月晦') > -1) return 'yuemo';
        if (t.indexOf('月望') > -1) return 'yuewang';
        if (t.indexOf('三元') > -1) return 'sanyuan';
        if (t.indexOf('三尸') > -1) return 'sanshi';
        if (t.indexOf('中会') > -1) return 'zhonghui';
        if (t.indexOf('阴毒') > -1) return 'yindu';
        if (t.indexOf('万神') > -1) return 'wanshen';
        if (t.indexOf('五虚') > -1) return 'wuxu';
        if (t.indexOf('犯') > -1) return 'fanhai';
        return 'festival';
    }

    function getBuddhistYear(year) {
        return year + 543;
    }

    // 返回某日所有佛教节日/斋日事件（农历 + 阳历）
    // 参数：农历月、农历日、[阳历月]、[阳历日]
    function getEvents(lunarMonth, lunarDay, solarMonth, solarDay) {
        var events = [];

        function pad(n) { return (n < 10 ? '0' + n : '' + n); }

        var lKey = pad(lunarMonth) + '-' + pad(lunarDay);
        if (LunarFestivalMap[lKey]) {
            var parts = LunarFestivalMap[lKey]
                .split(/[，,、]/)
                .map(function (s) { return s.trim(); })
                .filter(function (s) { return s; });
            for (var i = 0; i < parts.length; i++) {
                events.push({ type: deriveEventType(parts[i]), name: parts[i] });
            }
        }

        if (solarMonth && solarDay) {
            var sKey = pad(solarMonth) + '-' + pad(solarDay);
            if (SolarFestivalMap[sKey]) {
                events.push({ type: 'festival', name: SolarFestivalMap[sKey] + '（阳历）' });
            }
        }

        return events;
    }

    function getLunarDate(date) {
        var year = date.getFullYear();
        var month = date.getMonth() + 1;
        var day = date.getDate();
        return solarToLunar(year, month, day);
    }

    return {
        getLunarDate: getLunarDate,
        getBuddhistYear: getBuddhistYear,
        getEvents: getEvents,
        solarToLunar: solarToLunar,
        getSolarTerm: function(year, month, day) { return getSolarTerm(year, month, day); }
    };
